"""The world's key `takers` (the sprint of 2026-10-21, builder L; ALGEBRA.md, The emission of a bound record is the click's act of the taker): its one value `bodies`, under which every laid body of a turned family standing in its holder's well is a taker with its own transition's unit and window read from the board at the lay, and every declared region NodeDetector beside them where the bodies carry one transition (src/event_universe/taker.py, frame.py); read by loader/world.py into `World.takers`; any other value refused by name."""

from __future__ import annotations

TAKERS, BODIES = "takers", "bodies"  # the key and its one value


def takers_of(value: object) -> bool:
    """The key's one value `bodies`, True; any other value refused by name."""
    if value != BODIES:
        raise ValueError(f"{TAKERS} is {BODIES!r} where every body in a well is a taker, got {value!r}")
    return True
