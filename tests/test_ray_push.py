from __future__ import annotations

from event_universe.core.integer import by_clock
from event_universe.events import RaySimulation, parse_ray_world

M, LIGHT = 0, 1
FAMILIES = [{"name": "m", "quantum": 0}, {"name": "light", "quantum": 1}]
PLUS_X = [1, 0, 0]
FAN = [2, 1, 0]


def bar(
    measured: list[dict[str, object]],
    *,
    ticks: int = 30,
    release: list[int] | None = None,
    shape: list[int] | None = None,
    boundary: dict[str, str] | None = None,
    directions: list[list[int]] | None = None,
    in_transit: list[dict[str, object]] | None = None,
) -> dict[str, object]:
    return {
        "law": "rays",
        "model_id": "ray-push-test",
        "shape": shape or [12, 1, 1],
        "boundary": boundary or {"y": "periodic", "z": "periodic"},
        "ticks": ticks,
        "K": 1 << 20,
        "N": 64,
        "release": release or [1, 1],
        "suspension": 0,
        "directions": directions or [],
        "families": FAMILIES,
        "measured": measured,
        "in_transit": in_transit or [],
    }


def source(charge: int, *, release_on: list[int] | None = None, content: int = 4) -> dict[str, object]:
    return {
        "position": [0, 0, 0],
        "family": "m",
        "amount": content,
        "fixed": True,
        "charge": charge,
        "directions": [release_on or PLUS_X],
    }


def probe(
    charge: int, *, content: int = 5, position: list[int] | None = None, **keys: object
) -> dict[str, object]:
    return {
        "position": position or [6, 0, 0],
        "family": "m",
        "amount": content,
        "fixed": True,
        "charge": charge,
        **keys,
    }


def reads_of(records: list[dict[str, object]], number: int) -> list[tuple[int, int, list[int]]]:
    return [
        (int(r["tick"]), int(r["amount"]), list(r["push"]))
        for r in records
        if r["event"] == "read" and r["measured"] == number
    ]


def run(world: dict[str, object]) -> tuple[RaySimulation, list[dict[str, object]]]:
    records: list[dict[str, object]] = []
    simulation = RaySimulation(parse_ray_world(world), records.append)
    for _ in range(int(world["ticks"])):
        simulation.step()
        assert simulation.books()["balanced"]
    return simulation, records


def test_the_form_on_the_reviewers_world_its_sign_and_the_uncharged_probe():
    """(a), (b), (c)."""
    for source_charge, probe_charge, electric, pushed in (
        (3, 1, 192, -21760),
        (-3, 1, -192, -29440),
        (3, 0, 0, -25600),
    ):
        simulation, records = run(bar([source(source_charge), probe(probe_charge)]))
        reads = reads_of(records, 2)
        assert [tick for tick, _, _ in reads] == list(range(11, 31))
        for tick, amount, push in reads:
            assert amount == 4
            assert push == [-1280 + electric, 0, 0], (source_charge, probe_charge, tick)
            if electric:
                sign = 1 if source_charge * probe_charge > 0 else -1
                assert push[0] == -1280 + sign * by_clock(tick, 768, 4)
        assert simulation.measured[2].pushed == [pushed, 0, 0]
        store = simulation.stores[M]
        of_source = store.number == 1
        assert (store.charge[of_source] == source_charge).all() and (store.mass[of_source] == 4).all()


def test_the_cancellation_and_the_fractional_floor():
    """(d), (e)."""
    simulation, records = run(bar([source(2), probe(2, content=1)]))
    reads = reads_of(records, 2)
    assert len(reads) == 20 and all(push == [0, 0, 0] for _, _, push in reads)
    assert simulation.measured[2].pushed == [0, 0, 0]

    simulation, records = run(bar([source(3), probe(1)], release=[1, 2]))
    reads = reads_of(records, 2)
    assert [tick for tick, _, _ in reads] == list(range(11, 31))
    for tick, amount, push in reads:
        assert amount == 2
        assert push == [-640 + by_clock(tick, 384, 4), 0, 0], tick
        assert push[0] == -544
    assert simulation.measured[2].pushed == [-10880, 0, 0]


def test_a_paid_ray_pushes_by_its_label_and_the_paid_momentum_book_closes():
    """(f)."""
    lamp = {
        "position": [0, 0, 0],
        "family": "light",
        "amount": 1 << 23,
        "fixed": True,
        "lamp": {"rate": [1, 1], "directions": [PLUS_X]},
    }
    reader = probe(0, table={"light": "read"})
    world = bar([lamp, reader], release=[0, 1])
    records: list[dict[str, object]] = []
    simulation = RaySimulation(parse_ray_world(world), records.append)
    for _ in range(30):
        simulation.step()
        books = simulation.books()
        assert books["balanced"]
        momentum = books["momentum"]
        lamp_momentum = simulation.measured[1].momentum
        assert lamp_momentum == [-512 * simulation.tick, 0, 0]
        assert [
            a + b + c
            for a, b, c in zip(lamp_momentum, momentum["transit"], momentum["escaped"], strict=True)
        ] == [0, 0, 0], simulation.tick
    reads = reads_of(records, 2)
    assert [tick for tick, _, _ in reads] == list(range(11, 31))
    assert all(amount == 1 and push == [512, 0, 0] for _, amount, push in reads)
    assert simulation.measured[2].pushed == [10240, 0, 0]
    assert simulation.measured[1].momentum == [-15360, 0, 0]


