BOND = {"name": "bond", "quantum": 1, "phase": False, "lifetime": 3}
# The direction indices of the headings +x and -x in the table (the two rest
# slots, then the six headings in Port order).
PLUS_X = 2
MINUS_X = 3


def run(document: dict[str, object], ticks: int) -> tuple[NatureBeamSimulation, list[dict[str, object]]]:
    records: list[dict[str, object]] = []
    simulation = NatureBeamSimulation(parse_nature_beam_world(document), records.append)
    for tick in range(1, ticks + 1):
        simulation.step()
        books = simulation.books(recount=True)
        assert books["balanced"], tick
    return simulation, records


def contacts(records: list[dict[str, object]]) -> list[dict[str, object]]:
    return [r for r in records if r["event"] == "contact"]


def clicks(records: list[dict[str, object]], family: str) -> list[dict[str, object]]:
    return [r for r in records if r["event"] == "click" and r["family"] == family]


def momentum_sum(simulation: NatureBeamSimulation) -> list[int]:
    momentum = simulation.books(recount=True)["momentum"]
    return [
        a + b + c
        for a, b, c in zip(momentum["measured"], momentum["transit"], momentum["escaped"], strict=True)
    ]


