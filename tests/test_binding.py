def test_a_body_without_paid_content_contacts_as_before():
    """(d)."""
    q1: dict[str, object] = {"position": [2, 1, 2], "family": "q", "amount": 1, "fixed": True}
    q2: dict[str, object] = {"position": [2, 3, 2], "family": "q", "amount": 3, "fixed": True}
    worlds: list[tuple[dict[str, object], int]] = [
        (pair_world(1), 8),
        (pair_world(1, "read"), 5),
        (isolated(), 3),
        (isolated({"p": "rerelease"}), 3),
        (isolated(None, "h"), 3),
        (wide(300, [q1, q2]), 3),
        (order_world(True), 4),
        (order_world(False), 4),
    ]
    for document, ticks in worlds:
        world = parse_nature_beam_world(copy.deepcopy(document))
        assert world.binding is False and BINDING_RULE not in world.hypotheses
        simulation, records = run(document, ticks)
        handed = contacts(records)
        assert handed and all("given" not in r for r in handed)
        assert all(
            simulation.stores[f].size == 0 for f, family in enumerate(world.families) if not family.free
        )
    simulation, records = run(isolated(), 3)
    assert records == [
        {
            "event": "contact",
            "tick": 3,
            "number": 1,
            "node": [1, 2, 2],
            "to": [2, 2, 2],
            "occupant": 2,
            "family": "p",
            "rule": "measure",
            "axis": 0,
            "component": 256,
            "momentum": [0, 0, 0],
        }
    ]
    # A body of a paid family carries nothing of its own: no give.
    simulation, records = run(isolated(None, "h"), 3)
    body = simulation.measured[1]
    assert (
        body.held == [0, 0, 5]
        and body.momentum == [0, 0, 0]
        and simulation.measured[2].momentum == [256, 0, 0]
    )
    assert [(r["family"], r["component"]) for r in contacts(records)] == [("h", 256)]


