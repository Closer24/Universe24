def test_the_crowds_count_is_the_sum_over_the_owed_intervals():
    """(e)."""
    document = bar_world(200, ticks=80, extra={"suspension": [1, 8]})
    document["families"].append({"name": "c", "quantum": 0, "charge": 0, "phase": False})  # type: ignore[attr-defined]
    # The rule under test is the charging of the crowd's count, whatever the
    # clock counts; the presence word (clock-age-v1, 2026-09-21) keeps the
    # count the one the integers below were written for.
    document["measured"][0]["table"] = {"c": {"rule": "pass", "reads": "presence"}}  # type: ignore[index]
    document["measured"].append(  # type: ignore[attr-defined]
        {
            "position": [30, 0, 0],
            "family": "c",
            "amount": 1024,
            "fixed": True,
            "directions": [[-1, 0, 0]],
            "table": {"p": "pass"},
        }
    )
    document["release"] = [1, 512]
    simulation = NatureBeamSimulation(parse_nature_beam_world(document))
    body = simulation.measured[1]
    accumulator = 0
    summed = 0
    charged = 0
    for _ in range(80):
        simulation.step()
        summed += body.counted
        if body.creating:
            gained, accumulator = by_drive(accumulator, summed * 1, 8)
            charged += gained
            summed = 0
            assert body.counts.one("owed") == accumulator
            assert body.covariant is not None and body.covariant.counted_sum == 0
        else:
            assert body.covariant is not None and body.covariant.counted_sum == summed
    assert charged > 0 and body.waited >= charged


