def test_the_edge_of_no_momentum_with_a_push():
    """(c)."""
    events, simulation = run_in_process(pushed_world(256), 130)
    reader = simulation.measured[2]
    lines = [e for e in events if e["event"] == "energy" and e["number"] == 2]
    assert len(lines) == 130
    assert all(line["rest"] == 256 for line in lines)
    assert all(line["comparisons"] <= 4 for line in lines)
    assert all(line["energy"] ** 2 <= line["square"] < (line["energy"] + 1) ** 2 for line in lines)
    # Every arriving row pushes by -64; a step of the reader toward the
    # source reads the rows it met at once (two or three), still under the
    # ceiling of one grain.
    pushes = [e for e in events if e["event"] == "read" and e["measured"] == 2]
    assert pushes and all(e["push"][0] in (-64, -128, -192) for e in pushes)
    assert reader.momentum[0] == sum(e["push"][0] for e in pushes) <= -3584
    rises = [line["tick"] for line in lines if line["energy"] > 256]
    assert rises and all(line["energy"] == 256 for line in lines if line["tick"] < rises[0])
    # E' rises from E'_0 at the frame after the momentum reached 14 grains
    # (3 x 14^2 = 588 >= 2 x 256 + 1), the remainder in W.
    running, first = 0, None
    for push in pushes:
        running += push["push"][0]
        if running <= -3584:
            first = push["tick"]
            break
    assert rises[0] == first + 1
    assert lines[-1]["square"] == 256 * 256 + 3 * (abs(reader.momentum[0]) // 256) ** 2
    assert all(line["owed"] == 0 for line in lines if line["tick"] < rises[0])
    assert energy_root(256, 256 * 256 + 3 * 14 * 14) == (257, 3)
    assert energy_root(256, 256 * 256 + 3 * 13 * 13) == (256, 2)
    with pytest.raises(ValueError, match="ceiling of one grain 1"):
        run_in_process(pushed_world(1), 40)


