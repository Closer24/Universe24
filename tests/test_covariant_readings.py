def bar_world(
    momentum: int,
    *,
    key: bool = True,
    grain: int = 1,
    width: int = 1,
    content: int = 5,
    ticks: int = 60,
    release: list[int] | None = None,
    extra: dict[str, object] | None = None,
) -> dict[str, object]:
    document: dict[str, object] = {
        "law": "beam",
        "model_id": "covariant-bar",
        "shape": [41, 1, 1],
        "boundary": "open",
        "ticks": ticks,
        "K": 1 << 20,
        "N": 64,
        "release": release or [1, 1 << 20],
        "suspension": 0,
        "width": width,
        "families": [{"name": "p", "quantum": 0, "charge": 0, "phase": False}],
        "measured": [
            {"position": [5, 0, 0], "family": "p", "amount": content, "momentum": [momentum, 0, 0]}
        ],
    }
    if key:
        document["covariant_readings"] = {"c2": [1, 3], "grain": grain}
    if extra:
        document.update(extra)
    return document


def run_in_process(document: dict[str, object], ticks: int):
    """The events and the simulation of a world stepped in process, the books
    checked at every tick."""
    events: list[dict[str, object]] = []
    simulation = NatureBeamSimulation(
        parse_nature_beam_world(document), observer=events.append, keep_row_clicks=True
    )
    for _ in range(ticks):
        simulation.step()
        assert simulation.books()["balanced"], simulation.tick
    return events, simulation


def digests(folder: Path) -> dict[str, str]:
    record = json.loads((folder / "run.json").read_text(encoding="utf-8"))
    return {
        "state_sha256": hashlib.sha256((folder / "state.json").read_bytes()).hexdigest(),
        "audit_sha256": hashlib.sha256(json.dumps(record.get("audit", [])).encode("utf-8")).hexdigest(),
        "events_sha256": hashlib.sha256((folder / "events.jsonl").read_bytes()).hexdigest(),
    }


