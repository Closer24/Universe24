M, P, LIGHT = 0, 1, 2
Charge = int | list[int]
PLUS_X = [1, 0, 0]
FAN = [2, 1, 0]


def families(source_charge: Charge = 0, probe_charge: Charge = 0) -> list[dict[str, object]]:
    """The source's family `m`, the probe's family `p` (each free, its
    charge per unit of content declared) and the paid family `light`."""
    return [
        {"name": "m", "quantum": 0, "charge": source_charge},
        {"name": "p", "quantum": 0, "charge": probe_charge},
        {"name": "light", "quantum": 1},
    ]


def bar(
    measured: list[dict[str, object]],
    *,
    ticks: int = 30,
    release: list[int] | None = None,
    shape: list[int] | None = None,
    boundary: dict[str, str] | None = None,
    directions: list[list[int]] | None = None,
    in_transit: list[dict[str, object]] | None = None,
    source_charge: Charge = 0,
    probe_charge: Charge = 0,
) -> dict[str, object]:
    return {
        "law": "beam",
        "model_id": "ray-push-test",
        "shape": shape or [12, 1, 1],
        "boundary": boundary or {"y": "periodic", "z": "periodic"},
        "ticks": ticks,
        "K": 1 << 20,
        "N": 64,
        "release": release or [1, 1],
        "suspension": 0,
        "directions": directions or [],
        "families": families(source_charge, probe_charge),
        "measured": measured,
        "in_transit": in_transit or [],
    }


def source(*, release_on: list[int] | None = None, content: int = 4) -> dict[str, object]:
    return {
        "position": [0, 0, 0],
        "family": "m",
        "amount": content,
        "fixed": True,
        "directions": [release_on or PLUS_X],
    }


def probe(*, content: int = 5, position: list[int] | None = None, **keys: object) -> dict[str, object]:
    return {"position": position or [6, 0, 0], "family": "p", "amount": content, "fixed": True, **keys}


def reads_of(records: list[dict[str, object]], number: int) -> list[tuple[int, int, list[int]]]:
    return [
        (int(r["tick"]), int(r["amount"]), list(r["push"]))
        for r in records
        if r["event"] == "read" and r["measured"] == number
    ]


def run(world: dict[str, object]) -> tuple[NatureBeamSimulation, list[dict[str, object]]]:
    records: list[dict[str, object]] = []
    simulation = NatureBeamSimulation(parse_nature_beam_world(world), records.append)
    for _ in range(int(world["ticks"])):
        simulation.step()
        assert simulation.books()["balanced"]
    return simulation, records


def test_the_form_on_the_reviewers_world_its_sign_and_the_uncharged_probe():
    """(a), (b), (c)."""
    for source_charge, probe_charge, electric, pushed in (
        ([3, 4], [1, 5], 192, -21760),
        ([-3, 4], [1, 5], -192, -29440),
        ([3, 4], 0, 0, -25600),
    ):
        world = bar([source(), probe()], source_charge=source_charge, probe_charge=probe_charge)
        simulation, records = run(world)
        reads = reads_of(records, 2)
        assert [tick for tick, _, _ in reads] == list(range(11, 31))
        for tick, amount, push in reads:
            assert amount == 4
            assert push == [-1280 + electric, 0, 0], (source_charge, probe_charge, tick)
            if electric:
                sign = 1 if source_charge[0] > 0 else -1
                assert push[0] == -1280 + sign * by_clock(tick, 768, 4)
                assert push[0] == -1280 + sign * by_clock(tick, 256 * 3 * 1 * 5, 4 * 5)
        assert simulation.measured[2].pushed == [pushed, 0, 0]
        store = simulation.stores[M]
        # Nothing of the emitter on the record but the number: since the
        # amplitude law (2026-09-20) the four columns `record`, `branch`,
        # `multiplicity` and `birth` name the row's record, not its
        # emitter's factor, and since `hand-v1` (the same day) `hand` names
        # the row's own helicity, which no push reads.
        assert FIELDS == (
            "node",
            "direction",
            "age",
            "phase",
            "number",
            "amount",
            "content",
            "arrival",
            "record",
            "branch",
            "multiplicity",
            "birth",
            "hand",
            # The share's accumulators, the part of a record row's push not
            # yet delivered (record 155 of 2026-09-20, note 41 (viii)).
            "share_x",
            "share_y",
            "share_z",
            # The turn's remainder of the massive rows (`massive-rows-v1`,
            # 2026-09-21), which no push reads.
            "acc_turn",
        )
        assert not hasattr(store, "charge") and not hasattr(store, "mass")
        assert simulation.measured[1].charge == (3, 1) if source_charge[0] > 0 else (-3, 1)
        assert simulation.measured[2].charge == ((1, 1) if probe_charge else (0, 1))


