def outcome(gather: Json) -> str:
    return "".join(str(item[2]) for item in gather["chosen"])  # type: ignore[union-attr]


def correlation(counts: dict[str, int]) -> int:
    return sum(v if k[-2] == k[-1] else -v for k, v in counts.items())


def labelled(name: str, a: int, b: int) -> Json:
    world = AMPLITUDE.bell(name, (a, b))
    world["measured"][0]["lamp"]["branches"] = [[0, 1, 1], [3, 1, -1]]
    return world


def test_the_bell_pair_with_the_hand_as_the_labels_meaning():
    """(g)."""
    correlations: dict[tuple[int, int], int] = {}
    for a, b in AMPLITUDE.CHSH:
        world = labelled(f"bell_{a}_{b}", a, b)
        records: list[Json] = []
        simulation = NatureBeamSimulation(parse_nature_beam_world(world), records.append)
        for _ in range(int(world["ticks"])):  # type: ignore[call-overload]
            simulation.step()
            assert simulation.stores[0].size == 0 or set(simulation.stores[0].hand.tolist()) == {0}
        assert simulation.layer is not None
        first = (1 << 32) + 1
        gathers = [g for g in simulation.layer.gathers if first <= int(g["record"]) < first + 64]  # type: ignore[call-overload]
        assert len(gathers) == 64
        counts = dict(Counter(outcome(g) for g in gathers))
        assert sum(v for k, v in counts.items() if k[0] == "+") == 32
        assert sum(v for k, v in counts.items() if k[1] == "+") == 32
        correlations[(a, b)] = correlation(counts)
        clicks = [r for r in records if r["event"] == "click" and r["family"] == "light"]
        assert clicks and all(
            r["hand"] == (1, -1)[(label_of(int(r["branch"])) >> arm_of(int(r["branch"]))) & 1]  # type: ignore[call-overload]
            for r in clicks
        )
    assert correlations == {(0, 8): 44, (0, 24): -44, (16, 8): 44, (16, 24): 44}
    assert (
        correlations[(0, 8)] - correlations[(0, 24)] + correlations[(16, 8)] + correlations[(16, 24)]
        == 176
    )
    # The full mirror on the pair: the outcomes per u the same.
    world = labelled("bell_0_8", 0, 8)

    def outcomes(document: Json) -> list[tuple[int, str]]:
        simulation, _, _ = run(document)
        assert simulation.layer is not None
        return sorted((int(g["u"]), outcome(g)) for g in simulation.layer.gathers)  # type: ignore[call-overload]

    assert outcomes(world) == outcomes(transformed(world, MIRROR_X, full=True))


def plus_nodes(world: Json) -> set[tuple[int, ...]]:
    return {
        tuple(p)
        for d in world["detectors"]  # type: ignore[union-attr]
        if d["name"] in ("alice_plus", "bob_plus")
        for p in d["positions"]
    }


def filtered_pair(rotations: bool) -> Json:
    """`bell_0_8` with the label hands and `hand` +1 on the two plus
    counters, the rotations kept or removed."""
    world = labelled("bell_filter", 0, 8)
    plus = plus_nodes(world)
    for entry in world["measured"]:  # type: ignore[union-attr]
        if entry["family"] != "counter":
            continue
        table = dict(entry["table"]["light"]) if rotations else {}
        if tuple(entry["position"]) in plus:
            table["hand"] = 1
        entry["table"]["light"] = table
    return world


def chosen_sets(simulation: NatureBeamSimulation) -> list[tuple[str, ...]]:
    """The chosen sets of the lamp's first 64 records, by birth ordinal (the
    record's identity; since the fraction-free law of 2026-09-20 a paid
    lamp's exact clock stalls, so a tick window is not a count of births)."""
    assert simulation.layer is not None
    first = (1 << 32) + 1
    gathers = sorted(
        (g for g in simulation.layer.gathers if first <= int(g["record"]) < first + 64),  # type: ignore[call-overload]
        key=lambda g: int(g["record"]),  # type: ignore[call-overload]
    )
    assert len(gathers) == 64
    return [tuple(str(item[0]) for item in g["chosen"]) for g in gathers]  # type: ignore[union-attr]


