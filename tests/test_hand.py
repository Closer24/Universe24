def test_the_refusals_name_the_key():
    """(f)."""
    for value in (0, 2):
        with pytest.raises(ValueError, match=r"families\[0\]\.hand must be -1 or 1"):
            parse_nature_beam_world(bar([], [light(hand=value)], ticks=1))
    lamp: Json = {
        "position": [0, 0, 0],
        "family": "light",
        "amount": 1 << 10,
        "fixed": True,
        "lamp": {"wheel": [1, 64], "rate": [1, 1], "directions": [PLUS_X], "hand": 1},
    }
    with pytest.raises(ValueError, match=r"lamp\.hand \+1 differs from the family's hand -1"):
        parse_nature_beam_world(bar([lamp], [light(hand=-1)], ticks=1, K=64))
    families = [light(), {"name": "d", "quantum": 1, "phase": False}]
    with pytest.raises(
        ValueError, match=r"measured\[0\]\.axis \[1, 1, 0\] is not one of the six headings"
    ):
        parse_nature_beam_world(bar([{**reader("measure"), "axis": [1, 1, 0]}], families, ticks=1))
    with pytest.raises(ValueError, match=r"table\['light'\]\.hand is refused on pass"):
        parse_nature_beam_world(bar([reader({"rule": "pass", "hand": -1})], families, ticks=1))
    with pytest.raises(ValueError, match=r"in_transit\[0\]\.hand \+1 differs from the hand -1"):
        parse_nature_beam_world(bar([], [light(hand=-1)], ticks=1, in_transit=[transit(1, PLUS_X, 1)]))
    # The branches' hands against a family hand, and their own consistency.
    world = AMPLITUDE.bell("refusals", (0, 8))
    lamp_entry = world["measured"][0]["lamp"]

    def keyed(branches: list[list[int]], family_hand: int | None = None) -> Json:
        found = copy.deepcopy(world)
        found["measured"][0]["lamp"]["branches"] = branches
        if family_hand is not None:
            found["families"][0]["hand"] = family_hand
        return found

    assert lamp_entry["branches"] == [[0, 1], [3, 1]]
    with pytest.raises(ValueError, match=r"branches name the hands of their labels and the family"):
        parse_nature_beam_world(keyed([[0, 1, 1], [3, 1, -1]], family_hand=-1))
    with pytest.raises(ValueError, match=r"branches names a hand on some labels and not on others"):
        parse_nature_beam_world(keyed([[0, 1, 1], [3, 1]]))
    with pytest.raises(ValueError, match=r"gives the bit value 1 two hands"):
        parse_nature_beam_world(keyed([[1, 1, 1], [3, 1, -1]]))
    with pytest.raises(ValueError, match=r"gives both values of a label bit the hand \+1"):
        parse_nature_beam_world(keyed([[0, 1, 1], [3, 1, 1]]))
    parsed = parse_nature_beam_world(keyed([[0, 1, 1], [3, 1, -1]]))
    assert parsed.measured[0].lamp is not None and parsed.measured[0].lamp.label_hands == (1, -1)
    assert parsed.handed and parsed.hypotheses[-1] == HAND_RULE


