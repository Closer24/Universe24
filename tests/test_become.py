def test_the_clock_trigger_transforms_the_event_and_throws_its_products(tmp_path):
    """(a)."""
    document = world([neutron()])
    parsed = parse_nature_beam_world(document)
    assert parsed.hypotheses == [WEAK_RULE] and parsed.transformations
    assert parsed.measured[0].become is not None and parsed.measured[0].become.at == 3
    assert parsed.measured[0].become.products == ((BETA_, 1, 2), (NU_, 1, 0))
    assert parsed.owners(P_) == (1,) and parsed.owners(BETA_) == (1,) and parsed.owners(NU_) == (1,)
    simulation, records, books = run(document, 8)
    event = simulation.measured[1]
    assert event.held == [0, 5, 0, 0, 0] and event.family == P_ and event.became == 1
    assert event.momentum == [0, -64, 0] and event.become is None
    become = [r for r in records if r["event"] == "become"]
    assert become == [
        {
            "event": "become",
            "tick": 3,
            "node": [2, 2, 2],
            "measured": 1,
            "trigger": "clock",
            "triggered": 3,
            "from": "n",
            "into": "p",
            "products": [["beta", 1, 2, [0, 1, 0]], ["nu", 1, 0, [0, -1, 0]]],
            "recoil": [0, -64, 0],
            "counted": 0,
        }
    ]
    for tick, found in enumerate(books, start=1):
        assert found["charge"] == [0, 1], tick
        if tick >= 3:
            assert (
                line(found, "n", "measured")["became"] == -7
                and line(found, "p", "measured")["became"] == 5
            )
            assert line(found, "beta", "transit")["released"] == 1
            assert line(found, "beta", "content")["released"] == 2
            assert line(found, "nu", "transit")["released"] == 1
            assert line(found, "nu", "content")["released"] == 0
        else:
            assert (
                line(found, "n", "measured")["became"] == 0
                and line(found, "n", "measured")["current"] == 7
            )
    escapes = [
        (r["tick"], r["detector"], r["family"], r["content"], r["momentum"])
        for r in records
        if r["event"] == "click"
    ]
    assert escapes == [(8, "face:+y", "beta", 2, [0, 128, 0]), (8, "face:-y", "nu", 0, [0, -64, 0])]
    assert all(store.size == 0 for store in simulation.stores)
    state = event.state()
    assert state["became"] == 1 and state["family"] == P_ and state["held"] == [0, 5, 0, 0, 0]
    # The walk of the products before the escape.
    simulation, _, _ = run(document, 5)
    beta, nu = simulation.stores[BETA_], simulation.stores[NU_]
    assert int(beta.node[0]) == beta.flat((2, 3, 2)) and int(nu.node[0]) == nu.flat((2, 1, 2))
    assert int(beta.content[0]) == 2 and int(beta.phase[0]) == 0 and int(beta.age[0]) == 2
    # The record of a run.
    path = tmp_path / "world.json"
    path.write_text(json.dumps(world([neutron()], ticks=8)), encoding="utf-8")
    record = json.loads(
        run_initialization(path, tmp_path / "run", keep_row_clicks=True).read_text(encoding="utf-8")
    )
    assert record["status"] == "completed" and record["hypotheses"] == [WEAK_RULE]
    assert record["numbers"]["1"]["become"] == {
        "at": 3,
        "into": "p",
        "products": PRODUCTS,
        "crowd": None,
    }
    assert record["measured"][0]["became"] == 1 and record["measured"][0]["family"] == P_
    assert record["audit"][-1]["families"]["n"]["measured"]["became"] == -7
    # A trigger that never fires changes nothing: the same integers as no key.
    late, late_records, late_books = run(world([neutron({**BECOME, "at": 10**6})], ticks=20), 20)
    none, none_records, none_books = run(world([neutron(None)], ticks=20), 20)
    assert late_records == none_records == [] and late.measured[1].held == [7, 0, 0, 0, 0]
    assert [b["families"] for b in late_books] == [b["families"] for b in none_books]
    assert late.measured[1].state() == none.measured[1].state()


