BECOME: dict[str, object] = {"at": 3, "into": "p", "products": PRODUCTS}


def families(p_charge: object = None, beta_charge: object = -1) -> list[dict[str, object]]:
    return [
        {"name": "n", "quantum": 0, "phase": False},
        {"name": "p", "quantum": 0, "phase": False, "charge": [1, 5] if p_charge is None else p_charge},
        {"name": "beta", "quantum": 1, "charge": beta_charge},
        {"name": "nu", "quantum": 0},
        {"name": "w", "quantum": 0, "phase": False},
    ]


def neutron(become: dict[str, object] | None = BECOME, **keys: object) -> dict[str, object]:
    found: dict[str, object] = {"position": [2, 2, 2], "family": "n", "amount": 7, "fixed": True}
    if become is not None:
        found["become"] = become
    found.update(keys)
    return found


def world(measured: list[dict[str, object]], ticks: int = 12, **keys: object) -> dict[str, object]:
    document: dict[str, object] = {
        "law": "beam",
        "model_id": "become-test",
        "shape": [5, 5, 5],
        "boundary": "open",
        "ticks": ticks,
        "K": 1 << 20,
        "N": 64,
        "release": [1, 4096],
        "suspension": 0,
        "families": families(),
        "measured": measured,
    }
    document.update(keys)
    return document


def run(
    document: dict[str, object], ticks: int
) -> tuple[NatureBeamSimulation, list[dict[str, object]], list[dict[str, object]]]:
    records: list[dict[str, object]] = []
    simulation = NatureBeamSimulation(
        parse_nature_beam_world(document), records.append, keep_row_clicks=True
    )
    books: list[dict[str, object]] = []
    for tick in range(1, ticks + 1):
        simulation.step()
        found = simulation.books()
        assert found["balanced"], tick
        books.append(found)
    return simulation, records, books


def line(books: dict[str, object], family: str, kind: str) -> dict[str, object]:
    families_ = books["families"]
    assert isinstance(families_, dict)
    found = families_[family][kind]
    assert isinstance(found, dict)
    return found


