    """(b)."""
    parsed = parse_nature_beam_world(bar(0))
    assert parsed.hypotheses == [WEAK_RULE] and parsed.measured[1].transforms[NU_] is not None
    assert parsed.measured[1].transforms[NU_].at is None and parsed.measured[1].contact[NU_] == "measure"
