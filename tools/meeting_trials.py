"""The trials of a world of records declared NodeDetectors (examples/events/zeno, examples/events/anticoincidence; ALGEBRA.md, The click writes on the lattice (j); The click's read of the board; the paper's S.57 and S.59): one world file run once per value of a knob of the world the design names (`knob`, the lay's `amplitude` or the packets' `source` Node, and `knob_values`, the values; a design naming `seeds` is refused by name: the click reads the board and no seed exists, so the ensemble's variety is a knob of the world, each value a world of its own with its mode file regenerated by tools/pixel_mode.py as the folders' builders make them, `knobbed`, `one_trial`), over the design's `trial_intervals` (the world's `intervals`, the run's length, where the design names no trial length; one meaning per key: the one-vocabulary rename had turned the design's trial length into the run's key, so the control read 170 intervals for 48, found by the control run of 2026-10-05), and at the end the part each record stands in (its books, the reader's own), its windows closed (its books' count, the pulsed gate's n) and its `credit` lines labelled NODEDETECTOR naming `absorbed` or `emitted`, the clicks (the null window's LATTICE-labelled lines left out); the readings over the trials: per record the fraction of trials ending in each part and the windows closed per trial, the clicks per kind, the trials the run refused inside (the guard's refusal with its interval, by the knob's value, read and not hidden), and over the records the coincidence rows derived from the records' count (`coincidence_rows`): the fractions of trials with an absorption at every record alone and at every pair and no other, at neither, and per pair the anticoincidence parameter P(both) / (P(A) P(B)) where defined (A_only, B_only, both, neither and alpha for two records). Every number a click (the clicks, the parts the writes left) and no array is read; the tool holds no number of the law and compares nothing, the blind printed beside the readings where an expectation file is given.

Run with PYTHONPATH set to the checkout's src:

    PYTHONPATH=src python tools/meeting_trials.py --world <world>.json --design <design>.json [--expectation <expectation>.json] [--scratch <folder>]
"""

from __future__ import annotations

import argparse
import contextlib
import copy
import io
import json
import sys
import tempfile
from collections import Counter
from fractions import Fraction
from itertools import combinations
from pathlib import Path
from string import ascii_uppercase
from typing import Any

from event_universe.lattice import Lattice
from event_universe.world_files import load_world

KNOBS = (
    "amplitude",
    "source",
)  # the knobs a design may name: the packets' lay amplitude, their source Node


def knobbed(document: dict[str, Any], knob: str, value: int) -> dict[str, Any]:
    """The world document with the knob set on every packet and nothing else moved (the bodies, the detectors and the board stand): `amplitude` every packet's lay amplitude at the value; `source` every packet's top span along its axis moved together so that the first packet's source Node stands at the value (the packets' relative places kept, the edges untouched); another knob refused by name."""
    found = copy.deepcopy(document)
    packets = found.get("packets", [])
    if knob == "amplitude":
        for packet in packets:
            packet["amplitude"] = int(value)
    elif knob == "source":
        if packets:
            first = packets[0]
            offset = int(value) - int(first["top"][first["along"]][0])
            for packet in packets:
                span = packet["top"][packet["along"]]
                packet["top"][packet["along"]] = [int(span[0]) + offset, int(span[1]) + offset]
    else:
        raise ValueError(f"the design's knob is one of {list(KNOBS)}, got {knob!r}")
    return found


def one_trial(
    path: Path, knob: str, value: int, intervals: int, scratch: Path
) -> tuple[list[str], list[int], list[dict[str, object]], str | None]:
    """One run of the world with the knob at `value`: the world written into `scratch` with the knob set (`knobbed`) and its mode file regenerated beside it by tools/pixel_mode.py (the universe read by its repository path as the folder's builders do), run from its lay over `intervals`; the parts the records stand in at the end, by their declared names, their windows closed, the click lines, and the refusal where the run was refused inside (the guard's, or the read's by name, naming the interval; None otherwise)."""
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import pixel_mode  # noqa: PLC0415  # the mode generator beside this tool

    document = json.loads(path.read_text(encoding="utf-8"))
    scratch.mkdir(parents=True, exist_ok=True)
    world = scratch / f"{path.stem}_{knob}_{int(value)}.json"
    world.write_text(json.dumps(knobbed(document, knob, int(value))) + "\n", encoding="utf-8")
    with contextlib.redirect_stdout(io.StringIO()):  # the generator's own lines, not this tool's
        pixel_mode.main(["--input", str(world)])
    lines: list[dict[str, object]] = []
    board = Lattice(load_world(world), lines.append)
    refused = None
    try:
        for _ in range(intervals):
            board.step()
            if board.ended is not None:
                break
    except (
        RuntimeError
    ) as refusal:  # the guard: a level above the bound, the run refused at its interval
        refused = str(refusal)
    parts = [books.declared.names[books.part] for books in board.credit.bodies]
    windows = [books.windows for books in board.credit.bodies]
    clicks = [
        line
        for line in lines
        if line["event"] == "credit"
        and line["label"] == "NODEDETECTOR"
        and (line["absorbed"] or line["emitted"])
    ]
    return parts, windows, clicks, refused


def coincidence_rows(absorbed: Counter[tuple[int, ...]], bodies: int, trials: int) -> dict[str, object]:
    """The coincidence rows over the records, derived from their count and from no fixed key (the advisor's breaker and the mathematician's audit, #1793 comments 5981736108 K6, 5982140872 B3; the Boss's 5981734131 item 6; two hands): every record alone and every pair (`itertools.combinations` over the records), each row the trials with an absorption at those records and at no other (`absorbed`, the trials by the set of records that took), a record named by its letter in the world's order (A, B, C, ...), a row `<letters>_only` and `both` where the pair is every record, so that two records' rows read A_only, B_only, both, neither and alpha as the shipped two-body worlds' reports do; `neither` the trials with no absorption; and per pair the anticoincidence parameter P(both) / (P(A) P(B)) where defined, P(A) over the trials with an absorption at A whatever the others took, `alpha` for two records and `alpha_<letters>` beside; no row under two records (a coincidence is between records); a world of three records gets its three singles, its three pairs and `all`, the trials where every record took (the mathematician's note, #1793 comment 5982776069), so that every trial with an absorption stands in exactly one row."""
    if bodies < 2:
        return {}
    letters = [ascii_uppercase[number] for number in range(bodies)]
    rows: dict[str, object] = {}
    for size in range(1, bodies + 1):  # every subset of the records, the all-took trials their own row
        for subset in combinations(range(bodies), size):
            whole = "both" if bodies == 2 else "all"
            name = whole if size == bodies else "_".join(letters[n] for n in subset) + "_only"
            rows[name] = [absorbed[subset], trials]
    rows["neither"] = [absorbed[()], trials]
    for first, second in combinations(range(bodies), 2):
        a = sum(count for subset, count in absorbed.items() if first in subset)
        b = sum(count for subset, count in absorbed.items() if second in subset)
        both = sum(count for subset, count in absorbed.items() if first in subset and second in subset)
        alpha = Fraction(both * trials, a * b) if a and b else None
        name = "alpha" if bodies == 2 else f"alpha_{letters[first]}_{letters[second]}"
        rows[name] = [alpha.numerator, alpha.denominator] if alpha is not None else None
    return rows


def reading(
    path: Path, design: Path, expectation: Path | None, scratch: Path | None = None
) -> dict[str, object]:
    """The trials' readings over the design's knob and the trial's length (its keys `knob` and `knob_values`, and `trial_intervals`, or the world's `intervals`, the run's length, where the design names no trial length), each value one world run once (`one_trial`, built into `scratch`, a temporary folder where none is given), the blind beside them where given; a design naming `seeds` is refused by name."""
    declared = json.loads(design.read_text(encoding="utf-8"))
    world = json.loads(path.read_text(encoding="utf-8"))
    if "seeds" in declared:
        raise ValueError(
            f"{design} names `seeds`: the click reads the board and no seed exists; the trials vary a knob of the "
            f"world, `knob` (one of {list(KNOBS)}) over `knob_values`"
        )
    knob, values = str(declared["knob"]), [int(value) for value in declared["knob_values"]]
    intervals = int(declared.get("trial_intervals", world["intervals"]))
    folder = Path(tempfile.mkdtemp(prefix="meeting_trials_")) if scratch is None else scratch
    ends: list[Counter[str]] = []
    closed: list[Counter[int]] = []
    kinds: Counter[str] = Counter()
    absorbed: Counter[tuple[int, ...]] = Counter()
    refusals: dict[int, str] = {}
    for value in values:
        parts, windows, clicks, refused = one_trial(path, knob, value, intervals, folder)
        if refused is not None:
            refusals[value] = refused
            continue
        for number, (part, count) in enumerate(zip(parts, windows, strict=True)):
            while len(ends) <= number:
                ends.append(Counter())
                closed.append(Counter())
            ends[number][part] += 1
            closed[number][count] += 1
        kinds.update(
            f"{j['node_detector']} {j['realised']} by {j['absorbed'] or j['emitted']}" for j in clicks
        )
        absorbed[
            tuple(sorted({int(str(j["node_detector"]).split()[-1]) for j in clicks if j["absorbed"]}))
        ] += 1
    trials = len(values) - len(refusals)
    fractions = {
        f"body {n}": {part: [c, trials] for part, c in sorted(found.items())}
        for n, found in enumerate(ends)
    }
    windows_closed = {
        f"body {n}": {str(count): c for count, c in sorted(found.items())}
        for n, found in enumerate(closed)
    }
    coincidence = coincidence_rows(absorbed, len(ends), trials)
    found: dict[str, object] = {
        "world": path.name,
        "knob": knob,
        "knob_values": values,
        "trials": trials,
        "intervals": intervals,
        "ends_in_part": fractions,
        "windows_closed": windows_closed,
        "refused": {str(value): packet for value, packet in sorted(refusals.items())},
        "clicks": dict(sorted(kinds.items())),
        "coincidence": coincidence,
        "label": "NODEDETECTOR",
    }
    if expectation is not None:
        found["blind"] = json.loads(expectation.read_text(encoding="utf-8")).get("blind")
    return found


def main(argv: list[str] | None = None) -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--world", type=Path, required=True, help="the world file, its mode file beside it"
    )
    parser.add_argument(
        "--design", type=Path, required=True, help="the design file naming the knob and its values"
    )
    parser.add_argument("--expectation", type=Path, help="the blind expectation file, printed beside")
    parser.add_argument(
        "--scratch", type=Path, default=None, help="the folder the trials' worlds are built in"
    )
    args = parser.parse_args(argv)
    print(json.dumps(reading(args.world, args.design, args.expectation, args.scratch), indent=1))


if __name__ == "__main__":
    main()
