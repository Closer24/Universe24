def clump_ring(swing, lam, size=128, rounds=4000, window=500):
    """(m2)'s lay at 25 g n: every x at A (one Node-clock 1,000 more), every k on its valley, at rest; per window the
    spread of the Node-clocks' largest |x| in per mille of their mean, and its sign changes about the mean."""
    spring = 25 * gn
    k0 = n - quotient(g * swing * swing, 2 * spring)
    xs = [(swing + 1000, swing + 1000, 0)] + [(swing, swing, 0)] * (size - 1)
    ks = [(k0, k0, 0)] * size
    most = [0] * size
    out = []
    for t in range(1, rounds + 1):
        xs, ks = ring_round(xs, ks, lam, spring)
        most = [max(m, abs(s_[0])) for m, s_ in zip(most, xs, strict=True)]
        if carry(t, window, 0)[1] == 0:
            mean = quotient(sum(most), size)
            out.append((t, quotient(1000 * (max(most) - min(most)), mean), ring_changes([m - mean for m in most])))
            most = [0] * size
    return out


