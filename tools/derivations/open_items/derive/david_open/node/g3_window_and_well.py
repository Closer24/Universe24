def tenfold(trail, low, window=250):
    """A growth as a count over a span: the rounds from the first window whose largest |x| reaches `low` to the
    first that reaches ten times it, and that second window's end; None where the run holds no such window."""
    first = next((i for i, v in enumerate(trail) if v >= low), None)
    tens = next((i for i, v in enumerate(trail) if v >= 10 * low), None)
    if first is None or tens is None:
        return None
    return window * (tens - first), window * (tens + 1)


def tenfold_text(found, where):
    if found is None:
        return f"never within its rounds {where}"
    return f"in {found[0]} rounds {where} (by the window ending at round {found[1]})"


