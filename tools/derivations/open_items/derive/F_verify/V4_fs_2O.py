"""V4: the Frobenius-Schur indicators of the eight kinds of 2O from an explicit 2O (verifier of draft F, 1.5).

Exact: numbers a + b sqrt2 as pairs of Fractions; 2O as the 48 unit quaternions generated by (1 + i)/sqrt2 and
(1 + i + j + k)/2. chi_E1/2(h) = 2 w(h) (the trace of the SU(2) matrix); R(h) the rotation h v h^-1 (an integer
signed permutation); chi_E5/2 = chi_E1/2 chi_A2(R), chi_G3/2 = chi_E1/2 chi_E(R). Pass: |2O| = 48, the 24 images,
each spinor kind irreducible (mean |chi|^2 = 1), indicators +1 on the five kinds of O and -1 on the three spinor kinds.
Run: python3 -I V4_fs_2O.py [MUTANT]   MUTANT: none, square (chi(h)^2 read in place of chi(h^2))
"""

import sys
from fractions import Fraction as Fr

MUT = sys.argv[1] if len(sys.argv) > 1 else "none"
FAILS = []


def check(name, ok, detail=""):
    print(("PASS " if ok else "FAIL ") + name + (" : " + detail if detail else ""))
    if not ok:
        FAILS.append(name)


Z, ONE, HALF, S2 = (Fr(0), Fr(0)), (Fr(1), Fr(0)), (Fr(1, 2), Fr(0)), (Fr(0), Fr(1, 2))  # S2 = sqrt2 / 2


def ad(a, b):
    return (a[0] + b[0], a[1] + b[1])


def ng(a):
    return (-a[0], -a[1])


def ml(a, b):
    return (a[0] * b[0] + 2 * a[1] * b[1], a[0] * b[1] + a[1] * b[0])


def qm(p, q):
    w1, x1, y1, z1 = p
    w2, x2, y2, z2 = q
    return (ad(ad(ml(w1, w2), ng(ml(x1, x2))), ad(ng(ml(y1, y2)), ng(ml(z1, z2)))),
            ad(ad(ml(w1, x2), ml(x1, w2)), ad(ml(y1, z2), ng(ml(z1, y2)))),
            ad(ad(ml(w1, y2), ng(ml(x1, z2))), ad(ml(y1, w2), ml(z1, x2))),
            ad(ad(ml(w1, z2), ml(x1, y2)), ad(ng(ml(y1, x2)), ml(z1, w2))))


def qc(p):
    return (p[0], ng(p[1]), ng(p[2]), ng(p[3]))


gens = [(S2, S2, Z, Z), (HALF, HALF, HALF, HALF)]
group = {(ONE, Z, Z, Z)}
frontier = list(group)
while frontier:
    nxt = []
    for p in frontier:
        for g in gens:
            q = qm(p, g)
            if q not in group:
                group.add(q)
                nxt.append(q)
    frontier = nxt
G = sorted(group)
check("1 the generated group has 48 elements (2O)", len(G) == 48, str(len(G)))


def rot(h):
    """R(h) e_a = h e_a h^-1, as an integer matrix (columns the images of e_x, e_y, e_z)."""
    cols = []
    for a in range(3):
        e = [Z, Z, Z, Z]
        e[a + 1] = ONE
        v = qm(qm(h, tuple(e)), qc(h))
        assert v[0] == Z and all(c[1] == 0 and c[0].denominator == 1 for c in v[1:])
        cols.append([int(c[0]) for c in v[1:]])
    return tuple(tuple(cols[j][i] for j in range(3)) for i in range(3))


Rs = [rot(h) for h in G]
check("2 the 48 map onto the 24 rotations, two to one", len(set(Rs)) == 24 and all(Rs.count(R) == 2 for R in set(Rs)))


def perm_sign_fixed(R):
    perm = tuple(next(j for j in range(3) if R[j][i] != 0) for i in range(3))
    sgn = 1
    for i in range(3):
        for j in range(i + 1, 3):
            if perm[i] > perm[j]:
                sgn = -sgn
    return sgn, sum(1 for i in range(3) if perm[i] == i)


def chiO(kind, R):
    tr = R[0][0] + R[1][1] + R[2][2]
    sgn, fixed = perm_sign_fixed(R)
    return {"A1": 1, "A2": sgn, "E": fixed - 1, "T1": tr, "T2": sgn * tr}[kind]


def chi_half(h):
    return (2 * h[0][0], 2 * h[0][1])  # 2 w, as a + b sqrt2


def chi_spin(kind, h):
    c = chi_half(h)
    k = {"E1/2": 1, "E5/2": chiO("A2", rot(h)), "G3/2": chiO("E", rot(h))}[kind]
    return (k * c[0], k * c[1])


fs, norms = {}, {}
for kind in ("A1", "A2", "E", "T1", "T2"):
    tot = sum(chiO(kind, rot(qm(h, h))) if MUT != "square" else chiO(kind, rot(h)) ** 2 for h in G)
    fs[kind] = Fr(tot, 48)
for kind in ("E1/2", "E5/2", "G3/2"):
    tot = (Fr(0), Fr(0))
    nrm = Fr(0)
    for h in G:
        tot = ad(tot, chi_spin(kind, qm(h, h)) if MUT != "square" else ml(chi_spin(kind, h), chi_spin(kind, h)))
        c = chi_spin(kind, h)

    sq = (Fr(0), Fr(0))
    for h in G:
        c = chi_spin(kind, h)
        sq = ad(sq, ml(c, c))
    fs[kind] = (tot[0] / 48, tot[1] / 48)
    norms[kind] = (sq[0] / 48, sq[1] / 48)
print("   indicators:", {k: (str(v) if not isinstance(v, tuple) else f"{v[0]} + {v[1]} sqrt2") for k, v in fs.items()})
print("   spinor kinds' mean |chi|^2:", {k: f"{v[0]} + {v[1]} sqrt2" for k, v in norms.items()})
check("3 each spinor kind is irreducible (mean |chi|^2 = 1)", all(v == (1, 0) for v in norms.values()))
check("4 the five kinds of O have indicator +1 (real)", all(fs[k] == 1 for k in ("A1", "A2", "E", "T1", "T2")))
check("5 the three spinor kinds of 2O have indicator -1 (quaternionic): no kind of 2O is complex",
      all(fs[k] == (-1, 0) for k in ("E1/2", "E5/2", "G3/2")))
print("RESULT:", "ALL PASS" if not FAILS else "FAILED " + ", ".join(FAILS))
