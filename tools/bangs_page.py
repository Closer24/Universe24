def rows_of(path: str | Path) -> tuple[dict[int, dict[str, Any]], dict[str, dict[str, Any]]]:
    """A reading as its numbered rows and as its raw rows by key."""
    raw = {k: v for line in reading_lines(path) for k, v in line.items()}
    return reading_of(path), raw


def facts_of(
    record: dict[str, Any], rows: dict[int, dict[str, Any]], raw: dict[str, dict[str, Any]]
) -> dict[str, Any]:
    """The record's own numbers, read from its lines and its rows."""
    nodes = record.get("nodes", [])
    bang = next((v for k, v in raw.items() if k.startswith("1 ")), {})
    tops = next((v for k, v in raw.items() if k.startswith("1b ")), {})
    freezes = [(int(line["i"]), len(line["frozen"])) for line in nodes if line["frozen"]]
    shown = sorted(n for n, r in rows.items() if r["kind"] == "SHOWN")
    part = sorted(n for n, r in rows.items() if r["kind"] == "SHOWN in part")
    return {
        "intervals": int(record["intervals"]),
        "nodes": len(nodes[0]["X"]) if nodes else 0,
        "births": int(record["counts"]["births"]),
        "credits": int(record["counts"].get("body_clicks", 0)),
        "bangs": bang.get("bangs numbered (the interval each begins)", []),
        "returns": bang.get("exact returns to the seed's first state (interval)", []),
        "tops": tops.get("tops (interval)", []),
        "freezes": freezes,
        "run back": record.get("run_back"),
        "shown": shown,
        "part": part,
        "rows": len(rows),
    }


def brings_of(facts: dict[str, Any], rows: dict[int, dict[str, Any]]) -> tuple[list[str], list[str]]:
    """What the record brings from nature and what it lacks, read from its rows: the horizon (row 14) with its stopped clock (34), the recurrence (row 1), matter born (the births), the clicks and their laws (the credits and the rows read from the log)."""
    brings, lacks = [], []
    horizon, clock, recurs = rows[14]["kind"], rows[34]["kind"], rows[1]["kind"]
    if horizon.startswith("SHOWN"):
        brings.append(
            f"a horizon: {sum(n for _i, n in facts['freezes'])} frozen Node lines over {len(facts['freezes'])} intervals"
            + (
                ", the clock stopped at it"
                if clock.startswith("SHOWN")
                else f", the clock not read as stopped ({rows[34]['cause']})"
            )
        )
    else:
        lacks.append(f"a horizon ({rows[14]['cause'] or horizon})")
    if recurs.startswith("SHOWN"):
        brings.append(
            f"the bang recurring: {len(facts['returns'])} exact returns, {len(facts['bangs'])} bangs, the whole board turning at {len(facts['tops'])} tops"
        )
    else:
        lacks.append(f"the recurring bang ({rows[1]['cause']})")
    if facts["births"]:
        brings.append(f"matter born at the bang: {facts['births']} births")
    else:
        lacks.append("matter: no birth, so no law of the births is read")
    if facts["credits"]:
        brings.append(
            f"the bodies' own clicks: {facts['credits']} body credits, the laws read in the clicks among the {len(facts['shown'])} rows SHOWN"
        )
    else:
        lacks.append("the clicks: no body credit, so no law of the clicks is read")
    return brings, lacks


def esc(text: Any) -> str:
    return (
        str(text).replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace('"', "&quot;")
    )


def card_of(name: str, page: str, facts: dict[str, Any], brings: list[str], lacks: list[str]) -> str:
    """One bang's card: its page in a frame, its numbers, what it brings and what it lacks."""
    numbers = [
        f"{facts['intervals']:,} intervals on {facts['nodes']} Nodes; {facts['births']} births, {facts['credits']:,} body credits",
        "bangs at the intervals " + (", ".join(f"{i:,}" for i in facts["bangs"]) or "none"),
        "the whole board turning at once at " + (", ".join(f"{i:,}" for i in facts["tops"]) or "no top"),
        "frozen Nodes (interval: count) "
        + (
            ", ".join(f"{i:,}: {n}" for i, n in facts["freezes"][:8])
            + (" ..." if len(facts["freezes"]) > 8 else "")
            if facts["freezes"]
            else "none"
        ),
        f"gates seen: {len(facts['shown'])} of {facts['rows']} rows SHOWN"
        + (f", {len(facts['part'])} in part" if facts["part"] else "")
        + (
            f"; the run back exact {facts['run back']['exact']} of {facts['run back']['intervals']}"
            if facts.get("run back")
            else ""
        ),
    ]
    return (
        f'<section class="card"><h2>{esc(name)}</h2><iframe src="{esc(page)}" title="{esc(name)}" loading="lazy"></iframe>'
        + '<ul class="numbers">'
        + "".join(f"<li>{esc(n)}</li>" for n in numbers)
        + "</ul>"
        + '<p class="brings"><b>It brings:</b> '
        + esc("; ".join(brings) or "nothing of the three")
        + "</p>"
        + '<p class="lacks"><b>It lacks:</b> '
        + esc("; ".join(lacks) or "nothing of the three")
        + "</p></section>"
    )


def together_of(cards: list[tuple[str, dict[str, Any], dict[int, dict[str, Any]]]]) -> str:
    """What the records say together, counted: on how many of them the horizon, the recurrence and matter stand, and on how many all three at once."""
    three = [
        (r[14]["kind"].startswith("SHOWN"), r[1]["kind"].startswith("SHOWN"), f["births"] > 0)
        for _n, f, r in cards
    ]
    both = sum(1 for h, b, m in three if h and b and m)
    return (
        f"On the {len(cards)} records above, a horizon stands on {sum(h for h, _b, _m in three)}, the recurring bang on {sum(b for _h, b, _m in three)}, matter born at a bang on {sum(m for _h, _b, m in three)}; "
        + (f"all three together on {both}." if both else "no record carries all three at once.")
    )


def table_of(columns: list[tuple[str, dict[int, dict[str, Any]]]]) -> str:
    """Every numbered row by family, its phenomenon, and its verdict on every column's record."""
    numbers = {n for _name, rows in columns for n in rows}
    placed = {n for _f, ns in FAMILIES for n in ns}
    families = [*FAMILIES, ("other rows", tuple(sorted(numbers - placed)))]
    out = [
        "<table><thead><tr><th>row</th><th>the phenomenon</th>"
        + "".join(f"<th>{esc(name)}</th>" for name, _r in columns)
        + "</tr></thead><tbody>"
    ]
    for family, ns in families:
        rows = [n for n in ns if n in numbers]
        if not rows:
            continue
        out.append(f'<tr class="family"><td colspan="{2 + len(columns)}">{esc(family)}</td></tr>')
        for n in rows:
            phenomenon = next((rows_[n]["phenomenon"] for _name, rows_ in columns if n in rows_), "")
            cells = "".join(
                f'<td class="{CLASSES.get(r[n]["kind"], "not")}" title="{esc(str(r[n]["verdict"])[:160])}">{esc(r[n]["kind"])}</td>'
                if n in r
                else "<td></td>"
                for _name, r in columns
            )
            out.append(f"<tr><td>{n}</td><td>{esc(phenomenon)}</td>{cells}</tr>")
    out.append("</tbody></table>")
    return "".join(out)


