def page_of(bangs: list[tuple[str, dict[str, Any], str, str]], beside: list[tuple[str, str]]) -> str:
    """The whole page from the bangs (name, record, reading path, page path) and the readings beside (name, reading path)."""
    cards: list[tuple[str, dict[str, Any], dict[int, dict[str, Any]]]] = []
    html: list[str] = []
    for name, record, reading, page in bangs:
        rows, raw = rows_of(reading)
        facts = facts_of(record, rows, raw)
        brings, lacks = brings_of(facts, rows)
        cards.append((name, facts, rows))
        html.append(card_of(name, Path(page).name, facts, brings, lacks))
    columns = [(name, rows) for name, _facts, rows in cards] + [
        (name, reading_of(path)) for name, path in beside
    ]
    count = max((len(rows) for _n, rows in columns), default=0)
    return (
        '<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1">'
        f"<title>The bangs</title><style>{STYLE}</style></head><body><main>"
        f'<h1>The bangs</h1><p class="lead">{len(bangs)} records run from the seed alone, each played by its own page, each with what it brings from nature and what it lacks, read from its rows; beneath them the {count} rows of the gates with their verdicts.</p>'
        '<div class="bangs">' + "".join(html) + "</div>"
        '<h3>In plain words</h3><div class="words">'
        + "".join(f"<div><b>{esc(t)}</b><p>{esc(w)}</p></div>" for t, w in WORDS)
        + "</div>"
        + f"<p><b>Together:</b> {esc(together_of(cards))}</p>"
        + "<h3>Every row of the gates, by family, with its verdict on each record</h3>"
        + table_of(columns)
        + "</main></body></html>"
    )


def main(argv: list[str]) -> None:
    out, bangs, beside, flag = Path(argv[1]), [], [], False
    for arg in argv[2:]:
        if arg == "--beside":
            flag = True
            continue
        name, paths = arg.split("=", 1)
        if flag:
            beside.append((name, paths))
        else:
            record_path, reading, page = paths.split(":")
            with open(record_path, encoding="utf-8") as f:
                bangs.append((name, json.load(f), reading, page))
    out.write_text(page_of(bangs, beside), encoding="utf-8")


